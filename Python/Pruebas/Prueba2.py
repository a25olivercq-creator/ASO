# Programa que pide la edad de dos personas: Pepe y Mar
# Devuelve
# - Pepe es mayor que Mar
# Mar es mayor que PePe
# Mar y Pepe tienen la misma edad

edadPepe = 50
edadMar = 40

if edadPepe > edadMar:
    print ("Pepe es mator que Mar")
elif edadMar > edadPepe:
    print ("Mar es mayor que Pepe")
else:
    print ("Mar y Pepe tienen la misma edad")